const dicts: Record<Lang, Record<TKey, string>> = { en, ar };

export type Params = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, params?: Params): string {
  let s: string = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}

export const isRtl = (lang: Lang) => lang === 'ar';

/** Arabic-Indic digits read much more naturally in an Arabic UI. */
export function localizeDigits(value: string, lang: Lang): string {
  if (lang !== 'ar') return value;
  const map = '٠١٢٣٤٥٦٧٨٩';
  return value.replace(/\d/g, (d) => map[Number(d)]);
}
